import os
import shutil

def clean_data(dir_path):
  base_path = os.path.join(dir_path, 'PNEUMONIA')
  if not os.path.isdir(base_path):
    print(f"'{base_path}' not exist. PASS.")
    return
  # Create folders
  virus_folder = os.path.join(dir_path, 'PNEUMONIA_VIRUS')
  bact_folder = os.path.join(dir_path, 'PNEUMONIA_BACT')

  os.makedirs(virus_folder, exist_ok=True)
  os.makedirs(bact_folder, exist_ok=True)

  # Loop through files in base_path
  for filename in os.listdir(base_path):
      file_path = os.path.join(base_path, filename)

      # Check if it's a file and ends with .jpeg
      if os.path.isfile(file_path) and filename.endswith('.jpeg'):
          if '_virus_' in filename:
              shutil.move(file_path, os.path.join(virus_folder, filename))
          elif '_bacteria_' in filename:
              shutil.move(file_path, os.path.join(bact_folder, filename))
  print("Images successfully sorted into 'virus' and 'bact' folders.")

  # Count only files (not subfolders)
  file_count = len([f for f in os.listdir(base_path) if os.path.isfile(os.path.join(base_path, f))])

  if file_count < 2:
    shutil.rmtree(base_path)
    print(f"Deleted '{base_path}'.")
  else:
    print(f"WARNING: '{base_path}' still has some files.")

