from sklearn.metrics import confusion_matrix, precision_score, recall_score, f1_score, roc_auc_score, roc_curve, auc
from sklearn.preprocessing import label_binarize
import matplotlib.pyplot as plt
import torch
from tqdm import tqdm
import numpy as np
import seaborn as sns

def test_model(model, test_data_loader, criterion, num_classes, class_names=None):
    model.eval()
    test_loss = 0.0
    correct_test = 0
    total_test = 0

    all_labels = []
    all_preds = []
    all_probs = []

    with torch.no_grad():
        for test_images, test_labels in tqdm(test_data_loader, desc="Test data", leave=False):
            outputs = model(test_images)
            loss = criterion(outputs, test_labels)
            test_loss += loss.item()

            _, predicted = torch.max(outputs, 1)
            all_labels.extend(test_labels.cpu().numpy())
            all_preds.extend(predicted.cpu().numpy())

            probs = torch.softmax(outputs, dim=1)
            all_probs.extend(probs.cpu().numpy())

            total_test += test_labels.size(0)
            correct_test += (predicted == test_labels).sum().item()

    test_loss /= len(test_data_loader)
    test_accuracy = (correct_test / total_test) * 100

    # Metrics
    cm = confusion_matrix(all_labels, all_preds)
    precision = precision_score(all_labels, all_preds, average='macro')
    recall = recall_score(all_labels, all_preds, average='macro')
    f1 = f1_score(all_labels, all_preds, average='macro')

    try:
        if num_classes == 2:
            roc_auc = roc_auc_score(all_labels, np.array(all_probs)[:, 1])
        else:
            roc_auc = roc_auc_score(all_labels, all_probs, multi_class='ovr')
    except ValueError as e:
        roc_auc = None
        print(f"ROC AUC could not be calculated: {e}")

    # Display metrics
    print(f"Test Loss: {test_loss:.4f}")
    print(f"Test Accuracy: {test_accuracy:.2f}%")
    print(f"Precision (macro): {precision:.4f}")
    print(f"Recall (macro): {recall:.4f}")
    print(f"F1 Score (macro): {f1:.4f}")
    if roc_auc:
        print(f"ROC AUC (OvR): {roc_auc:.4f}")

    print("\nConfusion Matrix:")
    print(cm)

    # Plot Confusion Matrix
    plt.figure(figsize=(6, 4))
    sns.heatmap(cm, annot=True, fmt='d', cmap='Blues',
                xticklabels=class_names, yticklabels=class_names)
    plt.xlabel('Prédictions')
    plt.ylabel('Vérité réelle')
    plt.title('Matrice de confusion')
    plt.show()

    # ROC Curve plotting
    if num_classes == 2:
        fpr, tpr, thresholds = roc_curve(all_labels, [p[1] for p in all_probs])
        plt.figure()
        plt.plot(fpr, tpr, label=f"ROC curve (AUC = {roc_auc:.2f})")
        plt.plot([0, 1], [0, 1], 'k--')
        plt.xlabel("Taux de faux positifs")
        plt.ylabel("Taux de vrais positifs")
        plt.title("Courbe ROC")
        plt.legend(loc="lower right")
        plt.show()

    elif num_classes > 2:
        y_true_bin = label_binarize(all_labels, classes=list(range(num_classes)))
        all_probs_np = np.array(all_probs)

        plt.figure(figsize=(8, 6))
        for i in range(num_classes):
            fpr, tpr, _ = roc_curve(y_true_bin[:, i], all_probs_np[:, i])
            roc_auc_i = auc(fpr, tpr)
            class_label = class_names[i] if class_names else f"Classe {i}"
            plt.plot(fpr, tpr, label=f"{class_label} (AUC = {roc_auc_i:.2f})")

        plt.plot([0, 1], [0, 1], 'k--', label='Aléatoire')
        plt.xlabel('Taux de faux positifs')
        plt.ylabel('Taux de vrais positifs')
        plt.title('Courbes ROC (One-vs-Rest)')
        plt.legend(loc="lower right")
        plt.grid()
        plt.show()

    return {
        'loss': test_loss,
        'accuracy': test_accuracy,
        'precision': precision,
        'recall': recall,
        'f1_score': f1,
        'roc_auc': roc_auc,
        'confusion_matrix': cm
    }

