import random
from collections import defaultdict
from torch.utils.data import Subset

def get_train_val_subsets(dataset, samples_per_class_train: int, samples_per_class_val: int):
    class_indices = defaultdict(list)

    # Build class-to-indices mapping
    for idx, (image_path, label) in enumerate(dataset.samples):
        class_indices[label].append(idx)

    # Ensure reproducibility
    random.seed(42)

    train_indices = []
    val_indices = []

    for class_label, indices in class_indices.items():
        total_required = samples_per_class_train + samples_per_class_val

        if len(indices) >= total_required:
            selected_indices = random.sample(indices, total_required)
            train_selected = selected_indices[:samples_per_class_train]
            val_selected = selected_indices[samples_per_class_train:]
        else:
            print(f"Warning: Class {class_label} has only {len(indices)} samples.")
            split_point = min(samples_per_class_train, len(indices))
            train_selected = indices[:split_point]
            val_selected = indices[split_point:]

        train_indices.extend(train_selected)
        val_indices.extend(val_selected)

    train_subset = Subset(dataset, train_indices)
    val_subset = Subset(dataset, val_indices)

    return train_subset, val_subset

