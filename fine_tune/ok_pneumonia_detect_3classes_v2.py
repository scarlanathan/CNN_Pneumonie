"""**5.2. Fine-tune model**"""

import torch
import torch.optim as optim
import copy
import time
from tqdm import tqdm
import os

save_dir = '/content/drive/MyDrive/EPITECH/DEV-810/models/'  # For Google Drive
os.makedirs(save_dir, exist_ok=True)
save_path = os.path.join(save_dir, 'best_model_2c_v2s.pth')

# Hyperparameters
num_epochs = 10 #
patience = 3  # Number of epochs to wait for improvement in validation loss

criterion = torch.nn.CrossEntropyLoss()
optimizer = optim.AdamW(model.parameters(), lr=1e-4, weight_decay=1e-4)


# To track the best model and early stopping
best_val_loss = float('inf')
epochs_without_improvement = 0

# Train the model
for epoch in range(num_epochs):
    start_time = time.time()  # Start timing

    # Training phase
    model.train()
    train_loss = 0.0
    correct_train = 0
    total_train = 0

    for images, labels in tqdm(train_data_loader, desc=f"Training Epoch {epoch+1}/{num_epochs}", leave=False):
        optimizer.zero_grad()
        outputs = model(images)
        loss = criterion(outputs, labels)
        loss.backward()
        optimizer.step()

        train_loss += loss.item()
        _, predicted = torch.max(outputs, 1)
        total_train += labels.size(0)
        correct_train += (predicted == labels).sum().item()

    train_loss /= len(train_data_loader)
    train_accuracy = (correct_train / total_train) * 100

    # Validation phase
    model.eval()
    val_loss = 0.0
    correct_val = 0
    total_val = 0

    with torch.no_grad():
        for val_images, val_labels in tqdm(val_data_loader, desc=f"Validation Epoch {epoch+1}/{num_epochs}", leave=False):
            val_outputs = model(val_images)
            val_loss += criterion(val_outputs, val_labels).item()
            _, predicted = torch.max(val_outputs, 1)
            total_val += val_labels.size(0)
            correct_val += (predicted == val_labels).sum().item()

    val_loss /= len(val_data_loader)
    val_accuracy = (correct_val / total_val) * 100

    # End timing and calculate epoch duration
    epoch_duration = time.time() - start_time

    # Print statistics
    print(f"Epoch [{epoch+1}/{num_epochs}], "
          f"Train Loss: {train_loss:.4f}, Train Accuracy: {train_accuracy:.2f}%, "
          f"Validation Loss: {val_loss:.4f}, Validation Accuracy: {val_accuracy:.2f}%, "
          f"Epoch Time: {epoch_duration:.2f} seconds")

    # Early stopping and saving best model
    if val_loss < best_val_loss:
        best_val_loss = val_loss
        epochs_without_improvement = 0
        torch.save(model.state_dict(), save_path)
        print(f"Best model updated and saved to: {save_path}")
    else:
        epochs_without_improvement += 1

    if epochs_without_improvement >= patience:
        print(f"Early stopping triggered after {epoch+1} epochs with no improvement.")
        break

# Load best model weights
model.load_state_dict(torch.load(save_path))

